/** Stops the calling script when there is no build to check. */
export function requireDist() {
  if (!existsSync(DIST)) {
    console.error('dist/ is missing: run `npm run build` first.');
    process.exit(1);
  }
}

/**
 * Lists every HTML file under a directory.
 * @param {string} dir
 * @returns {string[]}
 */
export function htmlFiles(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return htmlFiles(path);
    return entry.name.endsWith('.html') ? [path] : [];
  });
}

/** Where `public/_headers` lands, with its placeholder replaced. */
export const HEADERS_FILE = join(DIST, '_headers');

/** Placeholder of `public/_headers` for the inline script hashes. */
export const HASHES_PLACEHOLDER = '{inline-script-hashes}';

/** Placeholder of `public/_headers` for the origin of the API. */
export const API_ORIGIN_PLACEHOLDER = '{api-origin}';

/** Placeholder of `public/_headers` for the CSP of the online checker. */
export const CHECKER_CSP_PLACEHOLDER = '{checker-csp}';

/**
 * Returns the CSP source of every inline script a page runs, such as
 * `'sha256-…'`. JSON-LD is data, not a script: the CSP does not apply to it.
 * @param {string} html
 * @returns {string[]}
 */
export function inlineScriptHashes(html) {
  return Array.from(html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script\b[^>]*>/gi))
    .filter(([, attributes = '']) => !/\ssrc\s*=|application\/ld\+json/i.test(attributes))
    .map(([, , body = '']) => `'sha256-${createHash('sha256').update(body).digest('base64')}'`);
}

/**
 * Returns the headers dist/_headers gives a URL path, as Cloudflare Pages
 * does: the values of a header set by several matching rules are joined with
 * a comma, and `! Name` drops what the rules above set. Supports the rules the
 * site uses: an exact path or a path ending in `*`.
 * @param {string} pathname
 * @returns {Record<string, string>}
 */
export function headersFor(pathname) {
  /** @type {Map<string, string>} */
  const headers = new Map();
  let matches = false;
  for (const line of readFileSync(HEADERS_FILE, 'utf8').split('\n')) {
    if (line.trim() === '' || line.trimStart().startsWith('#')) continue;
    if (!/^\s/.test(line)) {
      const rule = line.trim();
      matches = rule.endsWith('*') ? pathname.startsWith(rule.slice(0, -1)) : pathname === rule;
    } else if (matches) {
      const detached = /^\s*!\s+(.+)$/.exec(line)?.[1];
      if (detached) {
        headers.delete(detached.trim());
        continue;
      }
      const colon = line.indexOf(':');
      const name = line.slice(0, colon).trim();
      const value = line.slice(colon + 1).trim();
      const set = headers.get(name);
      headers.set(name, set ? `${set}, ${value}` : value);
    }
  }
  return Object.fromEntries(headers);
}

/**
 * Maps a URL path to the file Cloudflare Pages would serve, or null.
 * @param {string} pathname
 */
export function resolve(pathname) {
  const clean = decodeURIComponent(pathname).replace(/^\/+|\/+$/g, '');
  const candidates = [clean, join(clean, 'index.html'), `${clean}.html`];
  return (
    candidates
      .map((candidate) => join(DIST, candidate))
      // An encoded `..%2F` must not reach a file outside dist/.
      .filter((file) => file.startsWith(DIST))
      .find((file) => existsSync(file) && statSync(file).isFile()) ?? null
  );
}

/** @type {Record<string, string>} */
const CONTENT_TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8',
  '.json': 'application/json',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.woff2': 'font/woff2',
  '.xml': 'application/xml',
};

/** Content types Cloudflare Pages compresses: text, not PNG or WOFF2. */
const COMPRESSED = /^(?:text\/|application\/(?:json|xml)|image\/svg\+xml)/;

/**
 * Serves dist/ on a free local port the way Cloudflare Pages does, 404 page
 * and headers of dist/_headers included, text compressed: Lighthouse then
 * measures the bytes a visitor downloads.
 * @returns {Promise<{ origin: string, close: () => Promise<void> }>}
 */
export async function serveDist() {
  const server = createServer((request, response) => {
    const { pathname } = new URL(request.url ?? '/', 'http://localhost');
    const file = resolve(pathname);
    const status = file ? 200 : 404;
    const served = file ?? resolve('/404');
    if (!served) {
      response.writeHead(404).end();
      return;
    }
    readFile(served).then(
      (body) => {
        const type = CONTENT_TYPES[extname(served)] ?? 'application/octet-stream';
        const compress =
          COMPRESSED.test(type) && /\bgzip\b/.test(request.headers['accept-encoding'] ?? '');
        response
          .writeHead(status, {
            ...headersFor(pathname),
            'Content-Type': type,
            ...(compress && { 'Content-Encoding': 'gzip', Vary: 'Accept-Encoding' }),
          })
          .end(compress ? gzipSync(body) : body);
      },
      () => {
        response.writeHead(500).end();
      },
    );
  });
  await new Promise((done) => {
    server.listen(0, '127.0.0.1', () => {
      done(undefined);
    });
  });
  const address = server.address();
  if (address === null || typeof address === 'string') throw new Error('no server port');
  return {
    origin: `http://127.0.0.1:${String(address.port)}`,
    close: () =>
      new Promise((done) => {
        server.close(() => {
          done();
        });
      }),
  };
}
